/**
 * Decides what goes into the zips. The base zip is the installDir layout (see
 * `.claude/rules/portability-no-trace.md`): the exe, the seeds, empty folders kept as
 * placeholders, and a README. Only an allowlist of seed locations is read from the checkout, so a
 * developer's runtime state (vault, logs, cache, favourites) or generated folder cannot get in;
 * `assertCleanEntries` then checks the finished plan once more.
 */
import { lstat, readdir, readFile, stat } from 'node:fs/promises';
import { join } from 'node:path';

import { safeEntryPath, type ZipEntry } from './archive';
import {
  DEFAULT_SETTINGS,
  DIRECTORY_ONLY_DIRS,
  EXE_NAME,
  EXE_ZIP_PATH,
  LAUNCHER_DIR,
  MAINTAINER_DOCS,
  METADATA_ZIP_PATH,
  PLACEHOLDER,
  PLACEHOLDER_DIRS,
  PRODUCT,
  README_SOURCE,
  RUNTIME_NOTICE_ZIP_PATH,
  RUNTIME_ZIP_DIR,
  SEED_APP_DIR,
  SEED_TREES,
  SETTINGS_SEED,
} from './targets';

export interface StageOptions {
  /** The repo root (a temp folder in tests). */
  readonly root: string;
  /** The built program. */
  readonly exe: string;
  readonly version: string;
}

const encode = (text: string): Uint8Array => new TextEncoder().encode(text);
const bytes = (path: string, data: Uint8Array): ZipEntry => ({
  path,
  source: { kind: 'bytes', bytes: data },
});

/** Every file below `dir`, relative and `/` separated, sorted. Symbolic links are refused. */
export async function walk(dir: string, prefix = ''): Promise<string[]> {
  const found: string[] = [];
  const names = (await readdir(join(dir, prefix))).sort();
  for (const name of names) {
    const relative = prefix === '' ? name : `${prefix}/${name}`;
    const info = await lstat(join(dir, relative));
    if (info.isSymbolicLink()) throw new Error(`refusing to package a symbolic link: ${relative}`);
    if (info.isDirectory()) found.push(...(await walk(dir, relative)));
    else if (info.isFile()) found.push(relative);
  }
  return found;
}

/** The zip folders (and the exe) the base package is made of, for `assertCleanEntries`. */
const BASE_ALLOWED: readonly RegExp[] = [
  /^README\.md$/,
  new RegExp(`^${literal(EXE_ZIP_PATH)}$`),
  new RegExp(`^(${PLACEHOLDER_DIRS.map(literal).join('|')})/${literal(PLACEHOLDER)}$`),
  new RegExp(`^(${DIRECTORY_ONLY_DIRS.map(literal).join('|')})/$`),
  new RegExp(`^other/launcher/${literal(SETTINGS_SEED)}$`),
  new RegExp(`^${literal(METADATA_ZIP_PATH)}$`),
  /^other\/launcher\/documents\/[^/].*$/,
  /^other\/launcher\/licenses\/[^/].*$/,
  /^other\/launcher\/resources\/icons\/[^/]+\.svg$/,
];

/** The add-on zip: the runtime folder and its notice, nothing else. */
const RUNTIME_ALLOWED: readonly RegExp[] = [
  new RegExp(`^${literal(RUNTIME_ZIP_DIR)}/\\d+\\.\\d+\\.\\d+\\.\\d+-x64/[^/].*$`),
  new RegExp(`^${literal(RUNTIME_NOTICE_ZIP_PATH)}$`),
];

function literal(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
}

/** Folders and files that are build output, tooling state or secrets wherever they appear. */
const FORBIDDEN_SEGMENT =
  /(^|\/)(target|node_modules|dist|gen|autogenerated|\.git|\.genslate|\.turbo|\.claude|screenshots|ebwebview|vault-session|qa)(\/|$)/i;
const FORBIDDEN_NAME =
  /(^|\/)(\.env[^/]*|desktop\.ini|thumbs\.db|\.ds_store)$|\.(log|tmp|pml|bak)$/i;

/** `true` for a path that must never be shipped, whatever else is true of it. */
export function isForbiddenPath(path: string): boolean {
  return FORBIDDEN_SEGMENT.test(path) || FORBIDDEN_NAME.test(path);
}

/**
 * Throws, listing every offender, unless each entry is a safe name that belongs to the package:
 * `base` is the portable zip, `runtime` the WebView2 add-on.
 */
export function assertCleanEntries(entries: readonly ZipEntry[], kind: 'base' | 'runtime'): void {
  const allowed = kind === 'base' ? BASE_ALLOWED : RUNTIME_ALLOWED;
  const problems: string[] = [];
  for (const { path } of entries) {
    try {
      safeEntryPath(path);
    } catch (error) {
      problems.push(error instanceof Error ? error.message : String(error));
      continue;
    }
    // The fixed runtime has folders called EBWebView and gen... of its own: only the base
    // package is screened by name. Its shape is pinned by the allowlist.
    if (kind === 'base' && isForbiddenPath(path)) problems.push(`forbidden: ${path}`);
    else if (!allowed.some((pattern) => pattern.test(path)))
      problems.push(`not part of the ${kind} package: ${path}`);
  }
  if (problems.length > 0)
    throw new Error(['refusing to package:', ...problems.map((line) => `  ${line}`)].join('\n'));
}

/** The launcher's own metadata, stamped with the version being packaged. */
function launcherMetadata(version: string, identifier: string): string {
  return [
    '# Stamped by `bun run package`. Describes this build of the launcher.',
    '[app]',
    `name = ${JSON.stringify('SLATECORE LAUNCHER')}`,
    `description = ${JSON.stringify('The portable app launcher of the SLATECORE suite, by GENSLATE.')}`,
    `category = ${JSON.stringify('System')}`,
    '',
    '[build]',
    `version = ${JSON.stringify(version)}`,
    `identifier = ${JSON.stringify(identifier)}`,
    '',
    '[exe]',
    `windows = ${JSON.stringify(EXE_NAME)}`,
    '',
  ].join('\n');
}

async function bundleIdentifier(root: string): Promise<string> {
  const path = join(root, LAUNCHER_DIR, 'src-tauri', 'tauri.conf.json');
  const config = JSON.parse(await readFile(path, 'utf8')) as { identifier?: unknown };
  if (typeof config.identifier !== 'string' || config.identifier === '') {
    throw new Error(`${LAUNCHER_DIR}/src-tauri/tauri.conf.json has no identifier`);
  }
  return config.identifier;
}

async function assertExe(exe: string): Promise<void> {
  const info = await stat(exe).catch(() => undefined);
  if (info === undefined || !info.isFile()) throw new Error(`the launcher exe is missing: ${exe}`);
  if (info.size === 0) throw new Error(`the launcher exe is empty: ${exe}`);
}

/** The seed files of one tree below `SEED_APP_DIR`, keeping only non-empty ones. */
async function seedTree(root: string, tree: string): Promise<ZipEntry[]> {
  const base = join(root, SEED_APP_DIR, tree);
  const present = await stat(base).catch(() => undefined);
  if (present === undefined) return [];
  const entries: ZipEntry[] = [];
  for (const relative of await walk(base)) {
    const path = join(base, relative);
    // An empty seed (a document nobody wrote yet, a licence file still to fill) is a
    // placeholder: shipping a zero byte LICENSE would be worse than shipping none.
    if (relative.endsWith(`/${PLACEHOLDER}`) || relative === PLACEHOLDER) continue;
    if ((await stat(path)).size === 0) continue;
    const zipPath = `other/launcher/${tree}/${relative}`;
    // The runtime notice belongs to the add-on only; QA notes and other leftovers stay home.
    if (zipPath === RUNTIME_NOTICE_ZIP_PATH || isForbiddenPath(zipPath)) continue;
    // Documents for maintainers do not go to end users.
    if (tree === 'documents' && MAINTAINER_DOCS.includes(relative)) continue;
    entries.push({ path: zipPath, source: { kind: 'file', path } });
  }
  return entries;
}

/** The entries of `release/slatecore-launcher-<version>-base.zip`, sorted by name. */
export async function planBase(options: StageOptions): Promise<ZipEntry[]> {
  const { root, exe, version } = options;
  await assertExe(exe);

  const entries: ZipEntry[] = [{ path: EXE_ZIP_PATH, source: { kind: 'file', path: exe } }];
  for (const dir of PLACEHOLDER_DIRS) {
    entries.push(bytes(`${dir}/${PLACEHOLDER}`, new Uint8Array(0)));
  }
  for (const dir of DIRECTORY_ONLY_DIRS) entries.push({ path: `${dir}/`, source: { kind: 'dir' } });

  const readme = await readFile(join(root, README_SOURCE), 'utf8').catch(() => {
    throw new Error(`the packaged README is missing: ${README_SOURCE}`);
  });
  if (!readme.startsWith(`# ${PRODUCT}\n`)) {
    throw new Error(`${README_SOURCE} must start with the title "# ${PRODUCT}"`);
  }
  entries.push(bytes('README.md', encode(readme.replaceAll('{{version}}', version))));

  // The default settings come from a constant, never from the working tree: dev mode writes the
  // developer's own settings into the seed file.
  entries.push(bytes(`other/launcher/${SETTINGS_SEED}`, encode(DEFAULT_SETTINGS)));
  entries.push(
    bytes(METADATA_ZIP_PATH, encode(launcherMetadata(version, await bundleIdentifier(root)))),
  );
  for (const tree of SEED_TREES) entries.push(...(await seedTree(root, tree)));

  assertCleanEntries(entries, 'base');
  return entries.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

/** The facts stored beside the runtime, so the pinned source and hash travel with it. */
export interface RuntimeFacts {
  readonly version: string;
  readonly sha256: string;
  readonly source: string;
  readonly fileName: string;
}

/**
 * The entries of the WebView2 add-on: `other/shared/webview2/<version>-x64/` (the extracted
 * Fixed Version folder plus `runtime.json`) and the licence notice.
 */
export async function planRuntime(options: {
  readonly runtimeDir: string;
  readonly facts: RuntimeFacts;
  readonly notice: string;
}): Promise<ZipEntry[]> {
  const { runtimeDir, facts, notice } = options;
  const base = `${RUNTIME_ZIP_DIR}/${facts.version}-x64`;
  const entries: ZipEntry[] = [];
  for (const relative of await walk(runtimeDir)) {
    entries.push({
      path: `${base}/${relative}`,
      source: { kind: 'file', path: join(runtimeDir, relative) },
    });
  }
  entries.push(bytes(`${base}/runtime.json`, encode(`${JSON.stringify(facts, null, 2)}\n`)));
  entries.push(bytes(RUNTIME_NOTICE_ZIP_PATH, encode(notice)));
  assertCleanEntries(entries, 'runtime');
  return entries.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}
